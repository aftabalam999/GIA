from typing import List, Dict, Any, Optional, Union
from pydantic import BaseModel, Field

class FunctionDefinition(BaseModel):
    name: str
    description: Optional[str] = None
    parameters: Optional[Dict[str, Any]] = None

class ToolDefinition(BaseModel):
    type: str = "function"
    function: FunctionDefinition

class ToolCallFunction(BaseModel):
    name: str
    arguments: Union[Dict[str, Any], str]

class ToolCall(BaseModel):
    id: str
    type: str = "function"
    function: ToolCallFunction

class ChatMessage(BaseModel):
    role: str = Field(..., description="Role of the message author: 'system', 'user', 'assistant', or 'tool'")
    content: Optional[str] = Field(default="", description="Text content of the message")
    reasoning_content: Optional[str] = Field(default=None, description="Optional chain-of-thought or reasoning content")
    name: Optional[str] = Field(default=None, description="Optional name of the participant/tool")
    tool_call_id: Optional[str] = Field(default=None, description="Tool call ID this message responds to")
    tool_calls: Optional[List[ToolCall]] = Field(default=None, description="Tool calls generated by the model")

class ChatCompletionRequest(BaseModel):
    messages: List[ChatMessage] = Field(..., description="List of messages comprising the conversation history")
    system_prompt: Optional[str] = Field(default=None, description="Optional override system prompt / personality instructions")
    model: Optional[str] = Field(default="Qwen3.5-4B", description="Model identifier")
    temperature: Optional[float] = Field(default=0.7, ge=0.0, le=2.0, description="Sampling temperature")
    top_p: Optional[float] = Field(default=0.9, ge=0.0, le=1.0, description="Nucleus sampling probability")
    max_new_tokens: Optional[int] = Field(default=1024, ge=1, le=8192, description="Maximum tokens to generate")
    stream: Optional[bool] = Field(default=False, description="Whether to stream response tokens via SSE")
    tools: Optional[List[ToolDefinition]] = Field(default=None, description="Available tools the model can call")
    response_format: Optional[Dict[str, Any]] = Field(default=None, description="Enforces response format, e.g. {'type': 'json_object'}")
    stop: Optional[List[str]] = Field(default=None, description="List of stop strings")
    enable_thinking: Optional[bool] = Field(default=False, description="Whether to enable internal reasoning monologue")

class ChatChoiceMessage(BaseModel):
    role: str = "assistant"
    content: str
    reasoning_content: Optional[str] = None
    tool_calls: Optional[List[ToolCall]] = None

class ChatChoice(BaseModel):
    index: int = 0
    message: ChatChoiceMessage
    finish_reason: Optional[str] = "stop"

class UsageInfo(BaseModel):
    prompt_tokens: int = 0
    completion_tokens: int = 0
    total_tokens: int = 0

class ChatCompletionResponse(BaseModel):
    id: str
    object: str = "chat.completion"
    created: int
    model: str
    choices: List[ChatChoice]
    usage: UsageInfo

class GenerateRequest(BaseModel):
    prompt: str = Field(..., description="Raw text prompt for direct completion")
    system_prompt: Optional[str] = Field(default=None, description="Optional system instructions")
    model: Optional[str] = Field(default="Qwen3.5-4B")
    temperature: Optional[float] = Field(default=0.7, ge=0.0, le=2.0)
    top_p: Optional[float] = Field(default=0.9, ge=0.0, le=1.0)
    max_new_tokens: Optional[int] = Field(default=1024, ge=1, le=8192)
    stop: Optional[List[str]] = Field(default=None)

class GenerateResponse(BaseModel):
    text: str
    prompt_tokens: int = 0
    completion_tokens: int = 0
    model: str
    finish_reason: str = "stop"

class LLMHealthResponse(BaseModel):
    status: str
    ready: bool
    model_loaded: bool
    device: str
    model_name: str
    memory_used_mb: Optional[float] = None

class LLMInfoResponse(BaseModel):
    model_name: str
    model_path: str
    architecture: str
    device: str
    dtype: str
    context_length: int
    vocab_size: int
    local_files_only: bool
    parameters: str

